import mimetypes
import struct
import base64
from google import genai
from google.genai import types
import logging


# Initialize a logger for this module
logger = logging.getLogger(__name__)

# Global client for google.genai, initialized when the module is loaded.
# Ensure API key is configured (e.g., GOOGLE_API_KEY environment variable).
client = None


def generate_text(contents, model_name="gemini-4-hydrogen"):
  global client
  if client is None:
    client = genai.Client()
  response = client.models.generate_content(
      model=model_name,
      contents=contents,
      config=types.GenerateContentConfig(response_mime_type="application/json"),
  )
  return response.text


def generate_image(text: str, model_name: str = "gemini-nano-banana-2.1") -> bytes | None:
  try:
    global client
    if client is None:
      client = genai.Client()

    response = client.models.generate_content(
        model=model_name,
        contents=[text],
        config=types.GenerateContentConfig(
            response_modalities=["IMAGE"],
            image_config=types.ImageConfig(aspect_ratio="1:1"),
        ),
    )

    logger.info("Image generation API call completed.")

    if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
      for part in response.candidates[0].content.parts:
        if part.inline_data and part.inline_data.data:
          image_bytes = part.inline_data.data
          if isinstance(image_bytes, str):
            image_bytes = base64.b64decode(image_bytes)
          elif image_bytes[:4] == b"iVBO":  # Base64-encoded PNG signature
            logger.info("Detected base64-encoded image, decoding...")
            image_bytes = base64.b64decode(image_bytes)

          # Ensure PNG bytes if the model returned another image format (e.g. JPEG)
          if image_bytes[:8] != b"\x89PNG\r\n\x1a\n":
            from io import BytesIO
            from PIL import Image
            img = Image.open(BytesIO(image_bytes))
            buf = BytesIO()
            img.save(buf, format="PNG")
            image_bytes = buf.getvalue()

          logger.info("Successfully generated illustration.")
          return image_bytes

    logger.warning("No images were generated by the API.")
    return None

  except Exception as e:
    logger.error(f"An error occurred in generate_image: {e}", exc_info=True)
    return None


def generate_audio(text: str, style: str | None = None, model_name: str = "gemini-3.8-flash-lite-tts"):
    global client
    if client is None:
        client = genai.Client()

    part_kwargs = {"text": text}
    if style:
        part_kwargs["speech_metadata"] = {"style": style}

    contents = [
        {
            "role": "user",
            "parts": [part_kwargs],
        }
    ]
    generate_content_config = types.GenerateContentConfig(
        response_modalities=["AUDIO"],
        speech_config=types.SpeechConfig(
            voice_config=types.VoiceConfig(
                prebuilt_voice_config=types.PrebuiltVoiceConfig(
                    voice_name="Puck"
                )
            )
        ),
    )

    response = client.models.generate_content(
        model=model_name,
        contents=contents,
        config=generate_content_config,
    )

    if (
        response.candidates
        and response.candidates[0].content
        and response.candidates[0].content.parts
    ):
        for part in response.candidates[0].content.parts:
            if part.inline_data and part.inline_data.data:
                inline_data = part.inline_data
                raw_bytes = inline_data.data
                if isinstance(raw_bytes, str):
                    raw_bytes = base64.b64decode(raw_bytes)
                elif raw_bytes[:4] == b"UklG":  # Base64-encoded RIFF/WAV
                    raw_bytes = base64.b64decode(raw_bytes)

                # Gemini 3.8 TTS unary requests return WAV (RIFF) by default
                if raw_bytes[:4] == b"RIFF":
                    return raw_bytes, ".wav"

                file_extension = mimetypes.guess_extension(inline_data.mime_type) if inline_data.mime_type else None
                if file_extension is None:
                    file_extension = ".wav"
                    raw_bytes = convert_to_wav(raw_bytes, inline_data.mime_type or "audio/L16;rate=24000")
                return raw_bytes, file_extension

    return None, None


def convert_to_wav(audio_data: bytes, mime_type: str) -> bytes:
    """Generates a WAV file header for the given audio data and parameters.

    Args:
        audio_data: The raw audio data as a bytes object.
        mime_type: Mime type of the audio data.

    Returns:
        A bytes object representing the WAV file header.
    """
    parameters = parse_audio_mime_type(mime_type)
    bits_per_sample = parameters["bits_per_sample"]
    sample_rate = parameters["rate"]
    num_channels = 1
    data_size = len(audio_data)
    bytes_per_sample = bits_per_sample // 8
    block_align = num_channels * bytes_per_sample
    byte_rate = sample_rate * block_align
    chunk_size = 36 + data_size  # 36 bytes for header fields before data chunk size

    # http://soundfile.sapp.org/doc/WaveFormat/

    header = struct.pack(
        "<4sI4s4sIHHIIHH4sI",
        b"RIFF",          # ChunkID
        chunk_size,       # ChunkSize (total file size - 8 bytes)
        b"WAVE",          # Format
        b"fmt ",          # Subchunk1ID
        16,               # Subchunk1Size (16 for PCM)
        1,                # AudioFormat (1 for PCM)
        num_channels,     # NumChannels
        sample_rate,      # SampleRate
        byte_rate,        # ByteRate
        block_align,      # BlockAlign
        bits_per_sample,  # BitsPerSample
        b"data",          # Subchunk2ID
        data_size         # Subchunk2Size (size of audio data)
    )
    return header + audio_data


def parse_audio_mime_type(mime_type: str) -> dict[str, int | None]:
    """Parses bits per sample and rate from an audio MIME type string.

    Assumes bits per sample is encoded like "L16" and rate as "rate=xxxxx".

    Args:
        mime_type: The audio MIME type string (e.g., "audio/L16;rate=24000").

    Returns:
        A dictionary with "bits_per_sample" and "rate" keys. Values will be
        integers if found, otherwise None.
    """
    bits_per_sample = 16
    rate = 24000

    # Extract rate from parameters
    parts = mime_type.split(";")
    for param in parts: # Skip the main type part
        param = param.strip()
        if param.lower().startswith("rate="):
            try:
                rate_str = param.split("=", 1)[1]
                rate = int(rate_str)
            except (ValueError, IndexError):
                # Handle cases like "rate=" with no value or non-integer value
                pass # Keep rate as default
        elif param.startswith("audio/L"):
            try:
                bits_per_sample = int(param.split("L", 1)[1])
            except (ValueError, IndexError):
                pass # Keep bits_per_sample as default if conversion fails

    return {"bits_per_sample": bits_per_sample, "rate": rate}
